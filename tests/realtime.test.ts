import { expect, it, vi } from 'vitest';
const mock = vi.hoisted(() => ({ handlers: {} as Record<string, (event?: unknown) => void>, on: vi.fn(), disconnect: vi.fn(), removeAllListeners: vi.fn(), io: vi.fn() }));
vi.mock('socket.io-client', () => ({ io: mock.io }));
import { subscribeRideRealtime } from '@/services/ride-realtime';
it('uses one authenticated socket, reconnects, scopes events, and rejects invalid GPS', () => {
  vi.stubEnv('NEXT_PUBLIC_REALTIME_ORIGIN', 'https://backend.example.test');
  mock.io.mockReturnValue({ on: (event: string, callback: (event?: unknown) => void) => { mock.handlers[event] = callback; }, disconnect: mock.disconnect, removeAllListeners: mock.removeAllListeners });
  const callbacks = { onChange: vi.fn(), onConnection: vi.fn(), onLocation: vi.fn() };
  const off = subscribeRideRealtime('ride-id', 'action-token', callbacks);
  expect(mock.io).toHaveBeenCalledOnce();
  expect(mock.io.mock.calls[0][1].auth).toEqual({ role: 'rider', requestId: 'ride-id', token: 'action-token' });
  mock.handlers.connect();
  expect(callbacks.onConnection).toHaveBeenLastCalledWith(true);
  mock.handlers['ride:changed']({ requestId: 'other' });
  expect(callbacks.onChange).toHaveBeenCalledTimes(1);
  mock.handlers['ride:changed']({ requestId: 'ride-id' });
  expect(callbacks.onChange).toHaveBeenCalledTimes(2);
  const point = { requestId: 'ride-id', latitude: 6.5, longitude: 3.3, receivedAt: new Date().toISOString() };
  mock.handlers['ride:driver-location']({ ...point, latitude: NaN });
  mock.handlers['ride:driver-location']({ ...point, longitude: 181 });
  mock.handlers['ride:driver-location']({ ...point, receivedAt: 'invalid' });
  mock.handlers['ride:driver-location']({ ...point, requestId: 'other' });
  expect(callbacks.onLocation).not.toHaveBeenCalled();
  mock.handlers['ride:driver-location'](point);
  expect(callbacks.onLocation).toHaveBeenCalledOnce();
  mock.handlers.disconnect();
  expect(callbacks.onConnection).toHaveBeenLastCalledWith(false);
  off();
  expect(mock.disconnect).toHaveBeenCalledOnce();
  expect(mock.removeAllListeners).toHaveBeenCalledOnce();
  vi.unstubAllEnvs();
});
